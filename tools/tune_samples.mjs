#!/usr/bin/env node
// Measures each bundled piano sample with the app's own pitch detector and
// writes js/samples.js. Piano strings are slightly inharmonic, so the pitch you
// hear (and the pitch a detector reads) sits a few cents above the string's
// nominal f0. Calibrating with the same detector that scores the voice means
// the reference and the singer are measured with one ruler.
//
// It also level-matches the notes: `gain` brings every sample to the same
// loudness, measured with the lows rolled off (6 dB/oct below 250 Hz) the way
// both the ear and a small speaker roll them off. Raw piano samples differ by
// well over 10 dB note to note.
//
// Run by tools/build_samples.py. Needs ffmpeg.
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PitchDetector } from '../js/pitch.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SR = 48000;
const HOP = 512;
const FROM = 0.1; // seconds — skip the hammer transient
const TO = 1.3; // the part of the sample the app actually plays
const LOUDNESS = -15; // dBFS, weighted RMS every note is brought to (the app's limiter does the rest)
const MAX_GAIN = 5; // ~ +14 dB

const PC = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
const midiOf = (file) => {
  const [, letter, sharp, octave] = file.match(/^([A-G])(s?)(\d)\.mp3$/);
  return PC[letter] + (sharp ? 1 : 0) + 12 * (Number(octave) + 1);
};
const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return (s[Math.floor((s.length - 1) / 2)] + s[Math.ceil((s.length - 1) / 2)]) / 2;
};

function decode(file, filter) {
  const args = ['-v', 'error', '-i', join(ROOT, 'samples', file)];
  if (filter) args.push('-af', filter);
  const raw = execFileSync('ffmpeg', [...args, '-f', 'f32le', '-ac', '1', '-ar', String(SR), '-']);
  return new Float32Array(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));
}
function rmsDb(x) {
  let e = 0;
  const n = Math.min(x.length, Math.round(TO * SR));
  for (let i = 0; i < n; i++) e += x[i] * x[i];
  return 10 * Math.log10(e / n);
}

const det = new PitchDetector(SR);
const rows = [];
for (const file of readdirSync(join(ROOT, 'samples')).filter((f) => f.endsWith('.mp3'))) {
  const x = decode(file);
  const midi = midiOf(file);
  const nominal = 440 * 2 ** ((midi - 69) / 12);
  const readings = [];
  for (let i = Math.round(FROM * SR); i + det.size <= Math.min(x.length, TO * SR); i += HOP) {
    const r = det.detect(x.subarray(i, i + det.size));
    if (r.clarity >= 0.9) readings.push(1200 * Math.log2(r.freq / nominal));
  }
  const cents = Math.round(median(readings) * 100) / 100;
  const level = rmsDb(decode(file, 'highpass=f=250:poles=1'));
  const gain = Math.round(Math.min(MAX_GAIN, 10 ** ((LOUDNESS - level) / 20)) * 100) / 100;
  rows.push({ midi, file, cents, gain });
  console.log(`${file.padEnd(8)} ${cents >= 0 ? '+' : ''}${cents.toFixed(2)}¢  (${readings.length} frames)  level ${level.toFixed(1)} dB → gain ×${gain}`);
}
rows.sort((a, b) => a.midi - b.midi);

writeFileSync(
  join(ROOT, 'js', 'samples.js'),
  '// Generated by tools/tune_samples.mjs. Salamander Grand Piano V3, Alexander Holm, CC BY 3.0.\n' +
    "// cents = each sample's pitch vs 12-TET as read by js/pitch.js; the player corrects it out.\n" +
    '// gain = linear gain that brings each note to the same loudness.\n' +
    `export const SAMPLES = [\n  ${rows.map((r) => JSON.stringify(r)).join(',\n  ')},\n];\n`,
);
