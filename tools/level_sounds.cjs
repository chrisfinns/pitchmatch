#!/usr/bin/env node
// Levels the instruments against the EarMaster piano *as played*: every note
// goes through the app's real engine (envelope, transposition, limiter) in a
// headless browser, and each instrument's trim is searched until its median
// level over the vocal range matches the piano's (less MARGIN_DB).
// Writes js/levels.js. Run after tools/build_gm.mjs.
//
// Usage: node tools/level_sounds.cjs     Needs: Playwright with Chromium.
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

const ROOT = path.dirname(__dirname);
const MARGIN_DB = 1; // sit a touch under the piano: a steady tone reads louder than a decaying one
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.mp3': 'audio/mpeg', '.css': 'text/css' };

const server = http.createServer((req, res) => {
  const file = path.join(ROOT, decodeURIComponent(new URL(req.url, 'http://x').pathname));
  if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) return res.writeHead(404).end();
  res.writeHead(200, { 'content-type': TYPES[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});

server.listen(0, async () => {
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto(`${base}/index.html`);
  const result = await page.evaluate(async (margin) => {
    const { AudioEngine, outputChain, SOUNDS, TRIMS } = await import('/js/audio.js');
    const { INSTRUMENTS } = await import('/js/instruments.js');
    const SR = 48000;
    const NOTES = [40, 43, 47, 50, 53, 57, 60, 64, 67, 72, 76];
    const engine = new AudioEngine(); // shared file cache
    async function median(timbre) {
      const lv = [];
      for (const midi of NOTES) {
        const off = new OfflineAudioContext(1, SR * 1.6, SR);
        const e = new AudioEngine();
        e.ctx = off;
        e.files = engine.files;
        e.fetching = engine.fetching;
        const ch = outputChain(off);
        e.master = ch.input;
        e.side = ch.side;
        ch.output.connect(off.destination);
        engine.ctx = off;
        await engine.prepare([timbre], midi);
        e.playNote(midi, { at: 0, dur: 1.3, vel: 0.85, timbre });
        const x = (await off.startRendering()).getChannelData(0);
        let s = 0;
        for (let i = 0; i < 1.3 * SR; i++) s += x[i] * x[i];
        lv.push(10 * Math.log10(s / (1.3 * SR)));
      }
      lv.sort((a, b) => a - b);
      return lv[lv.length >> 1];
    }
    const target = (await median('piano')) - margin;
    const out = { target, trims: {}, levels: {} };
    for (const ins of INSTRUMENTS) {
      let lo = -36, hi = 6; // dB; output rises with trim
      for (let i = 0; i < 9; i++) {
        const mid = (lo + hi) / 2;
        TRIMS[ins.id] = mid;
        if ((await median(ins.id)) > target) hi = mid;
        else lo = mid;
      }
      TRIMS[ins.id] = Math.round(((lo + hi) / 2) * 10) / 10;
      out.trims[ins.id] = TRIMS[ins.id];
      out.levels[ins.id] = await median(ins.id);
    }
    return out;
  }, MARGIN_DB);
  await browser.close();
  server.close();

  console.log(`piano median ${(result.target + MARGIN_DB).toFixed(1)} dBFS; target ${result.target.toFixed(1)}`);
  for (const [id, t] of Object.entries(result.trims)) console.log(`${id.padEnd(12)} trim ${String(t).padStart(6)} dB → ${result.levels[id].toFixed(1)} dBFS`);
  fs.writeFileSync(
    path.join(ROOT, 'js', 'levels.js'),
    '// Generated by tools/level_sounds.cjs: per-instrument trim in dB, so every\n' +
      '// instrument plays as loud as the EarMaster piano through the output chain.\n' +
      `export const TRIM_DB = ${JSON.stringify(result.trims, null, 2)};\n`,
  );
});
